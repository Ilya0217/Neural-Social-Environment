# agent_dialogue_sim/prompts.py
from pydantic import BaseModel, Field
from typing import Literal, Optional

class AgentTurn(BaseModel):
    reply: str = Field(..., description="Текст реплики от лица текущего агента")
    tone: Literal["positive", "neutral", "negative"] = Field(..., description="Общая тональность")
    emotion: str = Field(..., description="Доминирующая эмоция (свободный текст на английском)")
    target: Optional[str] = Field(None, description="Кому адресована реплика (имя другого агента) или null")

